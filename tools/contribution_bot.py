"""Trusted issue-comment bridge: reserve work, review a Sheet snapshot, open a PR.

Standard library only. Never executes issue text or checks out a contributor branch.
The public community-work-state branch is the authoritative, atomic reservation log.
"""
from __future__ import annotations

import base64
import copy
import csv
import hashlib
import io
import json
import os
import pathlib
import re
import sys
import urllib.error
import urllib.parse
import urllib.request

from contribution_core import (WorkflowError, build_export, get_source, parse_snapshot,
                               reserve, snapshot_hash, snapshot_review, source_hash,
                               target_hash, validate_assignment)

ROOT = pathlib.Path(__file__).resolve().parent.parent
STATE_BRANCH = "community-work-state"
MAX_DOWNLOAD = 4 * 1024 * 1024


class ApiError(WorkflowError):
    def __init__(self, status, message):
        super().__init__(f"GitHub API {status}: {message}")
        self.status = status


class GitHub:
    def __init__(self, repository, token):
        if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
            raise WorkflowError("Invalid repository")
        self.repo = repository
        self.base = "https://api.github.com/repos/" + repository
        self.token = token

    def api(self, path, method="GET", data=None):
        request = urllib.request.Request(self.base + path, method=method, headers={
            "Authorization": "Bearer " + self.token,
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "Ebbtide-contributions",
            "Content-Type": "application/json",
        }, data=None if data is None else json.dumps(data).encode())
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                body = response.read()
                return json.loads(body) if body else None
        except urllib.error.HTTPError as error:
            # Return GitHub's message, never headers, tokens or raw response dumps.
            try:
                message = json.loads(error.read()).get("message", "request failed")
            except (ValueError, AttributeError):
                message = "request failed"
            raise ApiError(error.code, message) from None

    def is_maintainer(self, login):
        try:
            result = self.api("/collaborators/" + urllib.parse.quote(login) + "/permission")
            return result.get("permission") in {"admin", "maintain", "write"}
        except ApiError as error:
            if error.status == 404:
                return False
            raise

    def comment(self, issue, text):
        return self.api(f"/issues/{issue}/comments", "POST", {"body": text})

    def commit_files(self, parent, files, message):
        base = self.api("/git/commits/" + parent) if parent else None
        entries = []
        for path, content in files.items():
            blob = self.api("/git/blobs", "POST", {"content": content, "encoding": "utf-8"})
            entries.append({"path": path, "mode": "100644", "type": "blob", "sha": blob["sha"]})
        tree_data = {"tree": entries}
        if base:
            tree_data["base_tree"] = base["tree"]["sha"]
        tree = self.api("/git/trees", "POST", tree_data)
        return self.api("/git/commits", "POST", {"message": message, "tree": tree["sha"],
                         "parents": [parent] if parent else []})["sha"]


class State:
    def __init__(self, gh):
        self.gh = gh

    def ensure(self):
        try:
            self.gh.api("/git/ref/heads/" + STATE_BRANCH)
        except ApiError as error:
            if error.status != 404:
                raise
            sha = self.gh.commit_files(None, {
                "registry.json": json.dumps({"schema": 1, "assignments": []}, indent=2) + "\n",
                "README.md": "# Ebbtide work reservations\n\nGenerated by the trusted contribution workflow. "
                             "Use work-order issue commands; do not edit this branch manually.\n",
            }, "Initialize contribution reservations")
            try:
                self.gh.api("/git/refs", "POST", {"ref": "refs/heads/" + STATE_BRANCH, "sha": sha})
            except ApiError as race:
                if race.status != 422:
                    raise
                self.gh.api("/git/ref/heads/" + STATE_BRANCH)

    def read(self):
        sha = self.gh.api("/git/ref/heads/" + STATE_BRANCH)["object"]["sha"]
        return sha, self.read_file("registry.json", sha)

    def read_file(self, path, ref):
        item = self.gh.api("/contents/" + path + "?ref=" + urllib.parse.quote(ref))
        return json.loads(base64.b64decode(item["content"]))

    def mutate(self, operation):
        # Re-run the entire overlap/authorization check on the newest state after a race.
        for attempt in range(5):
            old_sha, state = self.read()
            state, files = operation(copy.deepcopy(state))
            files["registry.json"] = json.dumps(state, ensure_ascii=False, indent=2) + "\n"
            commit = self.gh.commit_files(old_sha, files, "Update contribution reservation")
            try:
                self.gh.api("/git/refs/heads/" + STATE_BRANCH, "PATCH", {"sha": commit, "force": False})
                return state
            except ApiError as error:
                if error.status not in {409, 422} or attempt == 4:
                    raise
        raise WorkflowError("Reservation busy; retry the command")


def issue_fields(body):
    sections = re.split(r"(?m)^### (.+)\s*$", body or "")
    return {sections[i].strip(): sections[i + 1].strip() for i in range(1, len(sections), 2)}


def assignment_from_issue(issue, source_root=ROOT):
    fields = issue_fields(issue.get("body"))
    labels = ["Kind", "Locale", "Table or voice role", "Contributor", "Reviewer",
              "Spreadsheet URL", "Sheet tab", "First key", "Last key"]
    if any(not fields.get(label) or fields[label] == "_No response_" for label in labels):
        raise WorkflowError("Use the Work order issue form and complete every field")
    url = urllib.parse.urlparse(fields["Spreadsheet URL"])
    match = re.fullmatch(r"/spreadsheets/d/([A-Za-z0-9_-]{20,100})(?:/.*)?", url.path)
    if url.scheme != "https" or url.netloc != "docs.google.com" or not match:
        raise WorkflowError("Spreadsheet URL must be a docs.google.com native spreadsheet link")
    assignment = {"issue": issue["number"], "kind": fields["Kind"], "locale": fields["Locale"],
                  "table": fields["Table or voice role"], "contributor": fields["Contributor"].lstrip("@"),
                  "reviewer": fields["Reviewer"].lstrip("@"), "spreadsheet_id": match[1],
                  "tab": fields["Sheet tab"]}
    source = get_source(source_root, assignment["kind"], assignment["table"])
    keys = [row["key"] for row in source]
    try:
        start, end = keys.index(fields["First key"]), keys.index(fields["Last key"])
    except ValueError:
        raise WorkflowError("First/last key must exist in the current source") from None
    if end < start:
        raise WorkflowError("Last key must follow First key in source order")
    assignment["keys"] = keys[start:end + 1]
    assignment["source_hash"] = source_hash(source)
    return validate_assignment(assignment, source), source


class SheetRedirects(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, request, fp, code, msg, headers, newurl):
        parsed = urllib.parse.urlparse(newurl)
        host = parsed.hostname or ""
        if parsed.scheme != "https" or not (host == "docs.google.com" or host.endswith(".googleusercontent.com")):
            raise WorkflowError("Sheet is not publicly readable; do not publish private staff files")
        return super().redirect_request(request, fp, code, msg, headers, newurl)


def fetch_sheet(assignment):
    # Construct the only permitted destination ourselves; no arbitrary URLs or credentials.
    columns = "A1:D5001" if assignment["kind"] == "ui" else "A1:L5001"
    query = urllib.parse.urlencode({"tqx": "out:csv", "sheet": assignment["tab"], "range": columns})
    url = "https://docs.google.com/spreadsheets/d/" + assignment["spreadsheet_id"] + "/gviz/tq?" + query
    try:
        with urllib.request.build_opener(SheetRedirects).open(url, timeout=30) as response:
            data = response.read(MAX_DOWNLOAD + 1)
            content_type = response.headers.get("Content-Type", "")
    except urllib.error.HTTPError as error:
        raise WorkflowError(f"Sheet export unavailable ({error.code}); it needs public reader access") from None
    if len(data) > MAX_DOWNLOAD or "html" in content_type.lower():
        raise WorkflowError("Sheet export is too large or is a sign-in page")
    try:
        return data.decode("utf-8-sig")
    except UnicodeDecodeError:
        raise WorkflowError("Sheet export is not UTF-8 CSV") from None


def current_assignment(state, issue):
    matches = [a for a in state["assignments"] if a["issue"] == issue]
    if len(matches) != 1:
        raise WorkflowError("This issue has no unique reservation. A maintainer must /work assign first")
    return matches[0]


def require_participant(gh, actor, assignment):
    if actor.lower() not in {assignment["contributor"].lower(), assignment["reviewer"].lower()} and not gh.is_maintainer(actor):
        raise WorkflowError("Only the assigned contributor, reviewer or maintainer can prepare this task")


def dispatch_checks(gh, branch, number):
    """Idempotently recover checks when bot-created PR events did not run them."""
    gh.api("/actions/workflows/check.yml/dispatches", "POST", {"ref": branch})
    default_branch = gh.api("")["default_branch"]
    gh.api("/actions/workflows/delivery-policy.yml/dispatches", "POST",
           {"ref": default_branch, "inputs": {"number": str(number)}})


def make_snapshot(assignment):
    source = get_source(ROOT, assignment["kind"], assignment["table"])
    # Runtime state fields are intentionally not part of the stable review digest.
    frozen = {key: value for key, value in assignment.items() if key not in {
        "status", "candidate", "approved_by", "approval_comment", "pr", "pr_url", "branch"}}
    result = parse_snapshot(fetch_sheet(frozen), frozen, source)
    result["target_hash"] = target_hash(ROOT, frozen)
    result["digest"] = snapshot_hash(result)
    build_export(ROOT, frozen, result)  # Validate existing destination before review, too.
    return result


def process(gh, state_store, issue, actor, command, digest=None, comment_id=None):
    number = issue["number"]
    if command == "assign":
        if not gh.is_maintainer(actor):
            raise WorkflowError("Only repository maintainers can assign or change a reservation")
        assignment, source = assignment_from_issue(issue)
        for login in {assignment["contributor"], assignment["reviewer"]}:
            # This endpoint is deliberately user-specific and not an arbitrary network request.
            request = urllib.request.Request("https://api.github.com/users/" + urllib.parse.quote(login),
                                             headers={"User-Agent": "Ebbtide-contributions"})
            try:
                with urllib.request.urlopen(request, timeout=15):
                    pass
            except urllib.error.HTTPError:
                raise WorkflowError("Contributor/reviewer must be existing GitHub usernames") from None
        state_store.mutate(lambda state: (reserve(state, assignment, source), {}))
        return (f"Reserved **{assignment['locale']} / {assignment['table']}**, {len(assignment['keys'])} keys, "
                f"for @{assignment['contributor']}; reviewer @{assignment['reviewer']}.\n\n"
                "The reservation is frozen. Editing the issue does not change it. "
                "Complete your assigned sheet cells, then comment `/work preview`.")

    _, state = state_store.read()
    assignment = current_assignment(state, number)
    if command == "preview":
        require_participant(gh, actor, assignment)
        if assignment["status"] not in {"assigned", "reviewed"}:
            raise WorkflowError("Task is not available for a new preview; close/sync its PR first")
        snapshot = make_snapshot(assignment)
        review_digest = snapshot["digest"]
        path = f"snapshots/{number}/{review_digest}"
        def preview_update(latest):
            item = current_assignment(latest, number)
            if item != assignment:
                raise WorkflowError("Reservation changed while preparing the preview; retry")
            item.update(status="assigned", candidate=review_digest)
            item.pop("approved_by", None)
            item.pop("approval_comment", None)
            return latest, {path + ".json": json.dumps(snapshot, ensure_ascii=False, indent=2) + "\n",
                            path + ".md": snapshot_review(snapshot)}
        state_store.mutate(preview_update)
        review_url = f"https://github.com/{gh.repo}/blob/{STATE_BRANCH}/{path}.md"
        return (f"[Review the frozen sheet snapshot]({review_url}).\n\nDigest: `{review_digest}`\n\n"
                f"Only @{assignment['reviewer']} can approve it with:\n\n`/work approve {review_digest}`\n\n"
                "Read every row before approving. Any source, sheet or target-file change requires a new preview.")

    if command == "release":
        if not gh.is_maintainer(actor):
            raise WorkflowError("Only maintainers can release a reservation")
        if assignment.get("pr"):
            pr = gh.api(f"/pulls/{assignment['pr']}")
            if pr["state"] == "open" or pr.get("merged_at"):
                raise WorkflowError("Close the unmerged PR first, or use /work sync after merge")
        def release_update(latest):
            item = current_assignment(latest, number)
            if item != assignment:
                raise WorkflowError("Reservation changed; retry release")
            item["status"] = "released"
            return latest, {}
        state_store.mutate(release_update)
        return "Reservation released. Use a new work-order issue for a replacement assignment."

    if command == "sync":
        if not gh.is_maintainer(actor):
            raise WorkflowError("Only maintainers can synchronize PR completion")
        return sync_pr(gh, state_store, assignment)

    if command != "approve":
        raise WorkflowError("Commands: /work assign, preview, approve <digest>, release, sync")
    if actor.lower() != assignment["reviewer"].lower() or actor.lower() == assignment["contributor"].lower():
        raise WorkflowError("Only the designated reviewer can approve; contributors cannot approve their own task")
    if not digest or not re.fullmatch(r"[0-9a-f]{64}", digest) or assignment.get("candidate") != digest:
        raise WorkflowError("Approve the current preview's complete 64-character digest")
    if assignment["status"] not in {"assigned", "reviewed", "pr_open"}:
        raise WorkflowError("Reservation is no longer active")
    snapshot = state_store.read_file(f"snapshots/{number}/{digest}.json", STATE_BRANCH)
    if snapshot_hash(snapshot) != digest or make_snapshot(assignment)["digest"] != digest:
        raise WorkflowError("Content changed since preview. Preview and review again; if source changed, release and create a fresh work order")
    path, csv_text = build_export(ROOT, snapshot["assignment"], snapshot)
    if target_hash(ROOT, snapshot["assignment"]) != snapshot["target_hash"]:
        raise WorkflowError("Target changed since review")
    branch = f"community/sheet-{number}-{digest[:12]}"
    if assignment.get("pr"):
        existing = gh.api(f"/pulls/{assignment['pr']}")
        if existing["state"] != "open":
            raise WorkflowError("PR was closed; synchronize it before doing further work")
        dispatch_checks(gh, assignment["branch"], existing["number"])
        return "A PR already exists: " + existing["html_url"]
    def approve_update(latest):
        item = current_assignment(latest, number)
        if item != assignment:
            raise WorkflowError("Reservation changed during approval; retry")
        item.update(status="reviewed", approved_by=actor, approval_comment=comment_id, branch=branch)
        return latest, {}
    state_store.mutate(approve_update)

    repository = gh.api("")
    base_branch = repository["default_branch"]
    base_sha = gh.api("/git/ref/heads/" + urllib.parse.quote(base_branch, safe=""))["object"]["sha"]
    checked_out = os.environ.get("CHECKED_OUT_SHA", "").strip()
    if not checked_out or checked_out != base_sha:
        raise WorkflowError("Default branch advanced during review. Retry in a fresh workflow run")
    # Stable branch and PR identity allows safe recovery after API/network interruption.
    try:
        branch_ref = gh.api("/git/ref/heads/" + urllib.parse.quote(branch, safe=""))
        item = gh.api("/contents/" + path + "?ref=" + branch_ref["object"]["sha"])
        if base64.b64decode(item["content"]).decode("utf-8") != csv_text:
            raise WorkflowError("Existing delivery branch differs from the approved export; maintainer review required")
    except ApiError as error:
        if error.status != 404:
            raise
        commit = gh.commit_files(base_sha, {path: csv_text}, f"Import reviewed {assignment['locale']} sheet for #{number}")
        gh.api("/git/refs", "POST", {"ref": "refs/heads/" + branch, "sha": commit})
    prs = gh.api("/pulls?state=open&head=" + urllib.parse.quote(gh.repo.split('/')[0] + ":" + branch, safe=""))
    if prs:
        pr = prs[0]
    else:
        review_url = f"https://github.com/{gh.repo}/blob/{STATE_BRANCH}/snapshots/{number}/{digest}.md"
        pr = gh.api("/pulls", "POST", {
            "base": base_branch, "head": branch,
            "title": f"{assignment['locale']}: reviewed {assignment['table']} sheet (#{number})",
            "body": (f"Imports {len(assignment['keys'])} reviewed strings from the assigned Google Sheet.\n\n"
                     f"Work order: #{number}\nContributor: @{assignment['contributor']}\n"
                     f"Sheet reviewer: @{actor}\n[Approved snapshot]({review_url})\n"
                     f"Snapshot SHA-256: `{digest}`\n\n"
                     "Format, source and placeholder checks ran before export. "
                     "Maintainer review and merge are still required. This does not update the game automatically."),
        })
    def pr_update(latest):
        item = current_assignment(latest, number)
        if item.get("candidate") != digest or item["status"] not in {"reviewed", "pr_open"}:
            raise WorkflowError("Reservation changed; PR requires maintainer reconciliation")
        item.update(status="pr_open", pr=pr["number"], pr_url=pr["html_url"])
        return latest, {}
    state_store.mutate(pr_update)
    # Explicit dispatch runs required 'check' even for bot-created PRs.
    dispatch_checks(gh, branch, pr["number"])
    return "Reviewed snapshot exported to " + pr["html_url"] + ". A maintainer must review and merge it."


def sync_pr(gh, store, assignment):
    if not assignment.get("pr"):
        raise WorkflowError("No PR is recorded for this reservation")
    pr = gh.api(f"/pulls/{assignment['pr']}")
    status = "completed" if pr.get("merged_at") else ("released" if pr["state"] == "closed" else "pr_open")
    def update(latest):
        item = current_assignment(latest, assignment["issue"])
        if item.get("pr") != pr["number"]:
            raise WorkflowError("Recorded PR changed; retry sync")
        item["status"] = status
        return latest, {}
    store.mutate(update)
    if status == "pr_open":
        dispatch_checks(gh, assignment["branch"], pr["number"])
    return "PR state synchronized: **" + status + "**."


def main():
    event = json.loads(pathlib.Path(os.environ["GITHUB_EVENT_PATH"]).read_text(encoding="utf-8"))
    gh = GitHub(os.environ["GITHUB_REPOSITORY"], os.environ["GH_TOKEN"])
    store = State(gh)
    if "pull_request" in event:
        if event.get("action") != "closed":
            return
        store.ensure()
        _, state = store.read()
        for a in state["assignments"]:
            if a.get("pr") == event["pull_request"]["number"]:
                gh.comment(a["issue"], sync_pr(gh, store, a))
        return
    if "comment" in event:
        if event["issue"].get("pull_request") or event.get("action") != "created":
            return
        body = event["comment"]["body"].strip()
        match = re.fullmatch(r"/work (assign|preview|approve|release|sync)(?: ([0-9a-f]{64}))?", body)
        if not match:
            return
        number, actor = event["issue"]["number"], event["comment"]["user"]["login"]
        command, digest = match.groups()
        comment_id = event["comment"]["id"]
    else:
        inputs = event.get("inputs", {})
        number = int(inputs["issue"])
        actor, command, digest = os.environ["GITHUB_ACTOR"], inputs["command"], inputs.get("digest")
        comment_id = None
        if not gh.is_maintainer(actor):
            raise WorkflowError("Workflow dispatch is for maintainers only")
    try:
        issue = gh.api(f"/issues/{number}")
        if issue.get("pull_request") or issue["state"] != "open":
            raise WorkflowError("Use an open work-order issue")
        store.ensure()
        message = process(gh, store, issue, actor, command, digest, comment_id)
        gh.comment(number, message)
        print(f"Completed {command} for issue #{number}")
    except (WorkflowError, urllib.error.URLError, TimeoutError) as error:
        message = str(error)
        gh.comment(number, "Work command stopped: " + message + "\n\nNo approval bypass was applied. Correct the problem and retry.")
        print("Work command stopped: " + message, file=sys.stderr)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
